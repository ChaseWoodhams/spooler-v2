"""Support grams per Object, read from a fixture G-code the way the slicer lays it out."""
import tempfile
import unittest
from pathlib import Path

import support_measure

# relative E (M83), an arc, retractions and unretracts, support split across two Objects and some outside any Object.
FIXTURE = """; generated by OrcaSlicer 2.4.2
M83
;TYPE:Outer wall
EXCLUDE_OBJECT_START NAME=cube_id_1_copy_0
G1 X10 Y10 E2.0 F1200
;TYPE:Support
G1 X20 Y10 E1.5
G1 E-0.8
G1 X30 Y30 F9000
G1 E0.8
G3 X40 Y30 I5 J0 E1.0 F1200
;TYPE:Support interface
G1 X50 Y30 E0.5
EXCLUDE_OBJECT_END NAME=cube_id_1_copy_0
;TYPE:Support
G1 X60 Y30 E0.25
EXCLUDE_OBJECT_START NAME=gate_id_2_copy_0
;TYPE:Outer wall
G1 X70 Y30 E3.0
;TYPE:Support
G2 X80 Y30 I5 J0 E2.0
;TYPE:Inner wall
G1 X90 Y30 E4.0
EXCLUDE_OBJECT_END NAME=gate_id_2_copy_0
; filament used [mm] = 14.5
; filament_diameter = 1.75
; filament_density = 1.25
"""


class SupportMeasureTests(unittest.TestCase):
    def measure(self, text=FIXTURE):
        with tempfile.TemporaryDirectory() as tmp:
            path = Path(tmp) / "plate.gcode"
            path.write_text(text)
            return support_measure.measure(path)

    def test_support_and_interface_extrusion_is_summed_per_object_and_for_the_plate(self):
        result = self.measure()
        self.assertEqual({n: round(o["support_mm"], 3) for n, o in result["objects"].items()},
                         {"cube_id_1_copy_0": 3.0, "gate_id_2_copy_0": 2.0})   # 1.5 + 1.0 + 0.5; retractions and unretracts not counted
        self.assertAlmostEqual(result["support_mm"], 5.25, places=3)           # includes the 0.25 mm outside any Object

    def test_grams_follow_filament_diameter_and_density(self):
        result = self.measure()
        per_mm = 3.14159265 * 0.875 ** 2 * 1.25 / 1000                          # mm3 per mm x g/cm3 / 1000
        self.assertAlmostEqual(result["objects"]["cube_id_1_copy_0"]["support_g"], 3.0 * per_mm, places=4)
        self.assertAlmostEqual(result["support_g"], 5.25 * per_mm, places=4)

    def test_a_plate_without_support_measures_zero(self):
        result = self.measure("M83\nEXCLUDE_OBJECT_START NAME=a\n;TYPE:Outer wall\nG1 X1 Y1 E1\nEXCLUDE_OBJECT_END NAME=a\n")
        self.assertEqual((result["objects"], result["support_mm"]), ({}, 0))

    def test_absolute_extrusion_is_measured_by_its_differences(self):
        text = ("M82\nEXCLUDE_OBJECT_START NAME=a\n;TYPE:Support\nG1 X1 Y1 E1\nG1 E0.5\nG1 X2 Y2\nG1 E1\nG1 X3 Y3 E2\n"
                "EXCLUDE_OBJECT_END NAME=a\n")   # +1, retract 0.5, unretract 0.5, +1
        self.assertAlmostEqual(self.measure(text)["objects"]["a"]["support_mm"], 2.0, places=3)


if __name__ == "__main__":
    unittest.main()
