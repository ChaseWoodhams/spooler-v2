import base64
import re
import tempfile
import unittest
import zlib
from pathlib import Path

import numpy as np

import thumbnails

PNG_SIGNATURE = b"\x89PNG\r\n\x1a\n"
CUBE_VERTS = np.array([(x, y, z) for x in (0, 20) for y in (0, 20) for z in (0, 20)], float) + [100, 100, 0]
CUBE_TRIS = np.array([(0, 1, 3), (0, 3, 2), (4, 6, 7), (4, 7, 5), (0, 4, 5), (0, 5, 1),
                      (2, 3, 7), (2, 7, 6), (0, 2, 6), (0, 6, 4), (1, 5, 7), (1, 7, 3)])


class ThumbnailTests(unittest.TestCase):
    def test_sizes_come_from_the_machine_preset(self):
        self.assertEqual(thumbnails.parse_sizes({"thumbnails": ["144x144"], "thumbnails_format": "PNG"}), [(144, 144)])
        self.assertEqual(thumbnails.parse_sizes({"thumbnails": "48x48/PNG, 300x300/PNG"}), [(48, 48), (300, 300)])
        self.assertEqual(thumbnails.parse_sizes({"thumbnails": ["144x144"], "thumbnails_format": "JPG"}), [])
        self.assertEqual(thumbnails.parse_sizes({}), [])

    def test_rendering_draws_the_model_on_a_transparent_background(self):
        png = thumbnails.render([(CUBE_VERTS, CUBE_TRIS)], 64, 48)

        self.assertEqual(png[:8], PNG_SIGNATURE)
        self.assertEqual(int.from_bytes(png[16:20], "big"), 64)
        self.assertEqual(int.from_bytes(png[20:24], "big"), 48)
        raw = zlib.decompress(png[png.index(b"IDAT") + 4:png.rindex(b"IEND") - 8])
        alpha = np.frombuffer(raw, np.uint8).reshape(48, 1 + 64 * 4)[:, 1:].reshape(48, 64, 4)[..., 3]
        self.assertEqual(alpha[0, 0], 0)
        self.assertGreater(int((alpha > 0).sum()), 200)
        self.assertGreater(int(alpha[24, 32]), 200)  # the cube sits in the middle

    def test_an_empty_plate_gives_a_blank_picture(self):
        self.assertEqual(thumbnails.render([], 16, 16)[:8], PNG_SIGNATURE)

    def test_block_goes_after_the_header_once(self):
        with tempfile.TemporaryDirectory() as tmp:
            path = Path(tmp) / "a.gcode"
            path.write_text("; HEADER_BLOCK_START\n; generated by OrcaSlicer 2.4.2\n; HEADER_BLOCK_END\n\nG28\nG1 X1\n")
            machine = {"thumbnails": ["32x32"], "thumbnails_format": "PNG"}

            self.assertEqual(thumbnails.add_to_gcode(path, machine, [(CUBE_VERTS, CUBE_TRIS)]), 1)
            self.assertEqual(thumbnails.add_to_gcode(path, machine, [(CUBE_VERTS, CUBE_TRIS)]), 0)  # never twice

            text = path.read_text()
            self.assertTrue(text.startswith("; HEADER_BLOCK_START"))
            self.assertLess(text.index("HEADER_BLOCK_END"), text.index("THUMBNAIL_BLOCK_START"))
            self.assertTrue(text.endswith("G28\nG1 X1\n"))
            length = int(re.search(r"thumbnail begin 32x32 (\d+)", text).group(1))
            lines = text.split("; thumbnail begin")[1].splitlines()[1:]
            body = "".join(line[2:] for line in lines[:lines.index("; thumbnail end")])
            self.assertEqual(len(body), length)
            self.assertEqual(base64.b64decode(body)[:8], PNG_SIGNATURE)


if __name__ == "__main__":
    unittest.main()
