class FakePrinter:
    def __init__(self, printer_id="p1", name="Printer 1"):
        self.id = printer_id
        self.name = name
        self.ip = "10.0.0.5"
        self.printer_type = "cc1"
        self.connected = True
        self.accept_start = True
        self.started = []
        self.set_status(0)

    def set_status(self, code, filename="", layer=0, total=0, machine=0):
        self.status = {"CurrentStatus": [machine], "PrintInfo": {
            "Status": code, "Filename": filename, "CurrentLayer": layer, "TotalLayer": total}}
        jobs.on_printer_status(self)

    async def start_print_file(self, filename, print_opts=None):
        self.started.append((filename, print_opts))
        return self.accept_start


class FakeWebSocket:
    def __init__(self):
        self.messages = []

    async def send(self, message):
        self.messages.append(json.loads(message))


def isolate_preflight(test: unittest.TestCase, data_dir: Path) -> None:
    """Keep preflight away from the real Spoolman and the real printer hardware settings."""
    for attr, value in (("loaded_spool", lambda printer: {"spool": None}),
                        ("HARDWARE_FILE", data_dir / "printer_hardware.json")):
        patcher = mock.patch.object(preflight, attr, value)
        patcher.start()
        test.addCleanup(patcher.stop)


class JobsTests(unittest.IsolatedAsyncioTestCase):
    def setUp(self):
        self._tmp = tempfile.TemporaryDirectory()
        self.dir = Path(self._tmp.name)
        self._saved_printers = state.printers
        database.configure(self.dir / "spooler.db")
        jobs.init(self.dir)
        self.printer = FakePrinter()
        self.other = FakePrinter("p2", "Printer 2")
        state.printers = {"p1": self.printer, "p2": self.other}
        self.uploads = []
        patcher = mock.patch.object(jobs, "uploader", self.fake_upload)
        patcher.start()
        self.addCleanup(patcher.stop)
        isolate_preflight(self, self.dir)

    async def asyncTearDown(self):
        for task in list(jobs._start_tasks.values()):
            task.cancel()
        await asyncio.sleep(0)

    def tearDown(self):
        state.printers = self._saved_printers
        database.configure(database.DB_FILE)
        jobs._data_dir = jobs.DATA_DIR
        self._tmp.cleanup()

    # helpers

    def fake_upload(self, ip, path, remote_name, progress):
        data = Path(path).read_bytes()
        self.uploads.append((ip, data, remote_name))
        progress(len(data), len(data))

    def add_job(self, name="cube.gcode", printer_id="p1", data=GCODE):
        return jobs.create_upload_job(io.BytesIO(data), len(data), name, printer_id)

    async def wait_for(self, predicate, timeout=3.0):
        deadline = time.monotonic() + timeout
        while not predicate():
            if time.monotonic() > deadline:
                self.fail("condition not reached in time")
            await asyncio.sleep(0.01)

    def job_state(self, job_id):
        return jobs.get_job(job_id)["state"]

    async def printing_job(self, name="cube.gcode", printer=None):
        printer = printer or self.printer
        job = self.add_job(name, printer.id)
        await jobs.start_job(job["id"])
        await self.wait_for(lambda: printer.started)
        printer.set_status(13, name, 10, 100)
        self.assertEqual(self.job_state(job["id"]), "printing")
        return job

    # creating and editing

    def test_upload_creates_a_queued_job_with_stored_file_and_estimates(self):
        job = self.add_job()
        second = self.add_job("plate.gcode")

        self.assertEqual((job["state"], job["name"], job["file_name"], job["source"]),
                         ("queued", "cube", "cube.gcode", "upload"))
        self.assertEqual((job["estimate_s"], job["estimate_g"], job["file_size"]), (3723, 12.5, len(GCODE)))
        self.assertEqual((self.dir / job["stored_file"]).read_bytes(), GCODE)
        self.assertGreater(second["position"], job["position"])

    def test_upload_validation(self):
        with self.assertRaisesRegex(JobError, "Only .gcode"):
            self.add_job("cube.stl")
        with self.assertRaisesRegex(JobError, "empty"):
            self.add_job(data=b"")
        with self.assertRaises(JobError) as err:
            self.add_job(printer_id="nope")
        self.assertEqual(err.exception.status, 404)
        self.assertEqual(jobs.list_jobs(), [])
        stored = self.dir / "jobs"
        self.assertEqual(list(stored.iterdir()) if stored.exists() else [], [])

    def test_reorder_requires_every_queued_job(self):
        a, b, c = (self.add_job(f"{n}.gcode")["id"] for n in "abc")

        jobs.reorder([c, a, b])
        self.assertEqual([j["id"] for j in jobs.list_jobs()], [c, a, b])
        with self.assertRaises(JobError) as err:
            jobs.reorder([a, b])
        self.assertEqual(err.exception.status, 409)

    def test_assigning_balances_printers_by_estimated_time(self):
        def timed(name, minutes):
            job = self.add_job(name)
            with database.transaction() as conn:
                conn.execute("UPDATE jobs SET estimate_s = ? WHERE id = ?", (minutes * 60, job["id"]))
            return job["id"]
        long, a, b, c = timed("long.gcode", 240), timed("a.gcode", 100), timed("b.gcode", 80), timed("c.gcode", 60)

        assigned = {j["id"]: j["printer_id"] for j in jobs.assign_printers([long, a, b, c], ["p1", "p2"])}

        # the 4 h plate alone on one printer, the other three (4 h in all) on the other
        self.assertEqual(assigned[long], "p1")
        self.assertEqual({assigned[a], assigned[b], assigned[c]}, {"p2"})

    async def test_printer_and_options_change_only_while_queued(self):
        job = self.add_job()
        updated = jobs.update_job(job["id"], {"printer_id": "p2", "print_opts": {"leveling": 1, "junk": True}})
        self.assertEqual(updated["printer_id"], "p2")
        self.assertEqual(updated["print_opts"], {"timelapse": False, "leveling": True, "smooth_plate": False})

        await jobs.start_job(job["id"])
        with self.assertRaises(JobError):
            jobs.update_job(job["id"], {"printer_id": "p1"})
        self.assertEqual(jobs.update_job(job["id"], {"notes": "PETG, 0.4 nozzle"})["notes"], "PETG, 0.4 nozzle")

    # starting and following a job

    async def test_start_uploads_sends_start_and_follows_the_print_to_completion(self):
        job = self.add_job()
        started = await jobs.start_job(job["id"])
        self.assertEqual(started["state"], "starting")

        await self.wait_for(lambda: self.printer.started)
        self.assertEqual(self.uploads, [("10.0.0.5", GCODE, "cube.gcode")])
        self.assertEqual(self.printer.started, [("/local/cube.gcode", {})])

        self.printer.set_status(16, "cube.gcode")
        self.assertEqual(self.job_state(job["id"]), "printing")
        self.assertIsNotNone(jobs.get_job(job["id"])["started_at"])

        self.printer.set_status(13, "cube.gcode", 50, 100)
        self.printer.set_status(9, "cube.gcode", 100, 100)
        self.assertEqual(self.job_state(job["id"]), "completed")
        self.assertIsNone(jobs.active_job_for("p1"))
        events = [e["event"] for e in jobs.job_events(job["id"])]
        self.assertEqual([e for e in events if e != "printer_status"],
                         ["created", "preflight", "starting", "uploaded", "start_sent", "printing", "completed"])
        self.assertIn("printer_status", events)

    async def test_a_printer_runs_only_one_job_at_a_time(self):
        first = self.add_job("first.gcode")
        second = self.add_job("second.gcode")
        await jobs.start_job(first["id"])

        with self.assertRaises(JobError) as err:
            await jobs.start_job(second["id"])
        self.assertEqual(err.exception.status, 409)
        self.assertEqual(self.job_state(second["id"]), "queued")

        moved = await jobs.start_job(second["id"], "p2")
        self.assertEqual((moved["state"], moved["printer_id"]), ("starting", "p2"))

    async def test_busy_or_offline_printer_blocks_start(self):
        job = self.add_job()
        self.printer.set_status(13, "someone-elses.gcode")
        with self.assertRaisesRegex(JobError, "busy"):
            await jobs.start_job(job["id"])

        self.printer.set_status(0)
        self.printer.connected = False
        with self.assertRaisesRegex(JobError, "offline"):
            await jobs.start_job(job["id"])
        self.assertEqual(self.job_state(job["id"]), "queued")

    async def test_failed_upload_fails_the_job_and_frees_the_printer(self):
        job = self.add_job()
        with mock.patch.object(jobs, "uploader", side_effect=UploadError("printer rejected chunk")):
            await jobs.start_job(job["id"])
            await self.wait_for(lambda: self.job_state(job["id"]) == "failed")

        self.assertIn("printer rejected chunk", jobs.get_job(job["id"])["error"])
        self.assertIsNone(jobs.active_job_for("p1"))
        self.assertEqual(self.printer.started, [])
        await jobs.start_job(self.add_job("next.gcode")["id"])

    async def test_a_printer_still_receiving_the_upload_gets_time_to_settle(self):
        loop = asyncio.get_running_loop()

        def upload_then_transfer(ip, path, remote_name, progress):
            self.fake_upload(ip, path, remote_name, progress)
            # the printer reports "file transferring" (machine status 2) right after the upload, then goes back to idle
            loop.call_soon_threadsafe(lambda: self.printer.set_status(0, machine=2))
            loop.call_soon_threadsafe(lambda: loop.call_later(0.15, lambda: self.printer.set_status(0, machine=0)))
        job = self.add_job()
        with mock.patch.object(jobs, "uploader", upload_then_transfer), mock.patch.object(jobs, "SETTLE_POLL_S", 0.02):
            await jobs.start_job(job["id"])
            await self.wait_for(lambda: self.printer.started)
        self.assertEqual(self.printer.started, [("/local/cube.gcode", {})])

    async def test_a_printer_that_stays_busy_after_the_upload_fails_the_job_with_its_status(self):
        loop = asyncio.get_running_loop()

        def upload_then_stay_busy(ip, path, remote_name, progress):
            self.fake_upload(ip, path, remote_name, progress)
            loop.call_soon_threadsafe(lambda: self.printer.set_status(0, machine=2))
        job = self.add_job()
        with mock.patch.object(jobs, "uploader", upload_then_stay_busy), mock.patch.object(jobs, "SETTLE_POLL_S", 0.01),                 mock.patch.object(jobs, "SETTLE_TIMEOUT_S", 0.1):
            await jobs.start_job(job["id"])
            await self.wait_for(lambda: self.job_state(job["id"]) == "failed")
        self.assertIn("is busy (print status 0, machine status 2)", jobs.get_job(job["id"])["error"])
        self.assertEqual(self.printer.started, [])

