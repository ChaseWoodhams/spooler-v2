    async def test_how_a_print_ends_sets_the_outcome(self):
        cases = [((8, "a.gcode", 40, 100), "cancelled"),
                 ((0, "", 0, 0), "unknown")]
        for (code, filename, layer, total), outcome in cases:
            with self.subTest(outcome=outcome):
                job = await self.printing_job(f"{outcome}.gcode" if not filename else filename)
                self.printer.set_status(code, filename, layer, total)
                self.assertEqual(self.job_state(job["id"]), outcome)
                self.printer.started.clear()

        job = await self.printing_job("layers.gcode")
        self.printer.set_status(13, "layers.gcode", 120, 120)
        self.printer.set_status(0)
        self.assertEqual(self.job_state(job["id"]), "completed")

    async def test_finish_is_refused_while_the_printer_still_prints_the_job(self):
        job = await self.printing_job()
        with self.assertRaises(JobError) as err:
            await jobs.finish_job(job["id"], "failed")
        self.assertEqual(err.exception.status, 409)

        self.printer.connected = False
        finished = await jobs.finish_job(job["id"], "failed")
        self.assertEqual(finished["state"], "failed")
        self.assertIsNone(jobs.active_job_for("p1"))

    async def test_active_job_is_followed_again_after_a_restart(self):
        job = await self.printing_job()

        jobs.init(self.dir)  # Spooler restarts
        self.assertEqual(jobs.active_job_for("p1")["id"], job["id"])
        self.printer.set_status(9, "cube.gcode", 100, 100)
        self.assertEqual(self.job_state(job["id"]), "completed")

    async def test_requeue_puts_a_finished_job_at_the_front(self):
        waiting = self.add_job("waiting.gcode")
        job = await self.printing_job("retry.gcode")
        self.printer.set_status(8, "retry.gcode")

        requeued = jobs.requeue(job["id"])
        self.assertEqual((requeued["state"], requeued["error"]), ("queued", None))
        self.assertEqual([j["id"] for j in jobs.list_jobs() if j["state"] == "queued"], [job["id"], waiting["id"]])

    async def test_delete(self):
        job = await self.printing_job()
        with self.assertRaises(JobError):
            jobs.delete_job(job["id"])

        queued = self.add_job("other.gcode")
        jobs.delete_job(queued["id"])
        self.assertIsNone(jobs.get_job(queued["id"]))
        self.assertFalse((self.dir / "jobs" / str(queued["id"])).exists())

    async def test_manual_start_is_blocked_while_a_queued_job_runs(self):
        await self.printing_job()
        ws = FakeWebSocket()

        await handle_browser_message(ws, json.dumps(
            {"action": "start_print", "printer_id": "p1", "filename": "/local/other.gcode"}))

        self.assertIn("running queued job", ws.messages[-1]["message"])
        self.assertEqual(len(self.printer.started), 1)

    async def test_printer_file_job_stays_on_its_printer_and_skips_upload(self):
        job = jobs.create_printer_file_job("p1", "/local/benchy.gcode", {"print_time": 3600, "filament_mm": 1234.5})
        self.assertEqual((job["source"], job["estimate_s"], job["estimate_mm"]), ("printer", 3600, 1234.5))
        with self.assertRaises(JobError):
            jobs.update_job(job["id"], {"printer_id": "p2"})

        with self.assertRaisesRegex(JobError, "Review the preflight warnings"):  # its contents can't be inspected
            await jobs.start_job(job["id"])
        await jobs.start_job(job["id"], acknowledge_warnings=True)
        await self.wait_for(lambda: self.printer.started)
        self.assertEqual(self.uploads, [])
        self.assertEqual(self.printer.started, [("/local/benchy.gcode", {})])


