def _run_process(args: list, timeout: float) -> tuple:
    try:
        proc = subprocess.run(args, capture_output=True, text=True, errors="replace", timeout=timeout,
                              creationflags=NO_WINDOW)
    except subprocess.TimeoutExpired:
        raise SliceError(f"Slicing took longer than {int(timeout // 60)} min and was stopped")
    return proc.returncode, (proc.stdout or "") + (proc.stderr or "")


runner = _run_process  # replaced in tests


def explain_exit(code: int) -> str:
    return CLI_ERRORS.get(code, f"OrcaSlicer exited with code {code}")


def _add_thumbnail(source: Path, plates: list, bundle_dir: Path) -> None:
    """Give a single-plate STL/OBJ slice the picture the printer shows. Best effort: never fails the slice."""
    if len(plates) != 1 or source.suffix.lower() not in (".stl", ".obj"):
        return
    try:
        import thumbnails
        import trimesh
        mesh = trimesh.load(str(source), file_type=source.suffix.lower().lstrip("."), force="mesh")
        machine = json.loads((bundle_dir / "machine.json").read_text(encoding="utf-8"))
        thumbnails.add_to_gcode(plates[0], machine, [(mesh.vertices, mesh.faces)])
    except Exception as e:
        print(f"[Slicer] No thumbnail for {source.name}: {e}")


def run_slice(record: dict) -> dict:
    """Slice one record's model with its locked profile. Blocking."""
    orca = require_orca()
    bundle = load_bundle(record["bundle_id"])
    verify_bundle(bundle)
    source = _data_dir / record["source_file"]
    if not source.is_file():
        raise SliceError("The uploaded model is missing")

    work = slices_dir() / str(record["id"])
    profile, output = work / "profile", work / "output"
    for folder in (profile, output):
        shutil.rmtree(folder, ignore_errors=True)
        folder.mkdir(parents=True)
    bundle_dir = profiles_dir() / bundle["id"]
    for kind in ("machine", "filament"):
        shutil.copyfile(bundle_dir / f"{kind}.json", profile / f"{kind}.json")
    process = json.loads((bundle_dir / "process.json").read_text(encoding="utf-8"))
    process["curr_bed_type"] = BED_TYPES[record["bed_type"]]
    (profile / "process.json").write_bytes(json.dumps(process, indent=1, sort_keys=True).encode())
    (profile / "bundle.json").write_bytes(json.dumps(bundle, indent=1).encode())

    args = [str(orca), "--datadir", str(_data_dir / "slicer-data"), "--slice", "0",
            "--arrange", "0" if source.suffix.lower() == ".3mf" else "1",  # keep a project's own layout
            "--load-settings", f"{profile / 'machine.json'};{profile / 'process.json'}",
            "--load-filaments", str(profile / "filament.json"),
            "--outputdir", str(output), str(source)]
    started = time.monotonic()
    code, text = runner(args, SLICE_TIMEOUT_S)
    duration_ms = int((time.monotonic() - started) * 1000)
    code = code - (1 << 32) if code >= (1 << 31) else code  # Windows reports negative codes as unsigned
    (work / "slicer.log").write_text(f"$ {subprocess.list2cmdline(args)}\nexit code {code} after {duration_ms} ms\n"
                                     f"{text}", encoding="utf-8")
    if code != 0:
        raise SliceError(explain_exit(code), code)
    plates = sorted(output.glob("plate_*.gcode"), key=lambda p: int(re.sub(r"\D", "", p.stem) or 0))
    if not plates:
        raise SliceError("OrcaSlicer finished without producing G-code", code)

    _add_thumbnail(source, plates, bundle_dir)
    with plates[0].open("r", encoding="utf-8", errors="replace") as fh:
        generated = _GENERATED_BY.search(fh.read(4096))
    estimates = [read_estimates(p) for p in plates]
    return {
        "plates":         plates,
        "exit_code":      code,
        "duration_ms":    duration_ms,
        "slicer_version": f"{generated.group(1)} {generated.group(2)}" if generated else orca.parent.name,
        "estimate_s":     sum(e["estimate_s"] or 0 for e in estimates) or None,
        "estimate_g":     round(sum(e["estimate_g"] or 0 for e in estimates), 2) or None,
    }


def _create_jobs(record: dict, result: dict) -> list:
    """Turn each sliced plate into a queued print job. Blocking."""
    stem = Path(record["source_name"]).stem
    printer_id = record["printer_id"] if record["printer_id"] in state.printers else None
    job_ids = []
    for index, gcode in enumerate(result["plates"], start=1):
        name = safe_gcode_name(f"{stem}.gcode" if len(result["plates"]) == 1 else f"{stem}_plate{index}.gcode")
        with gcode.open("rb") as fh:
            job = jobs.create_upload_job(fh, gcode.stat().st_size, name, printer_id)
        jobs.update_job(job["id"], {"notes": record["notes"], "print_opts": record["print_opts"]})
        with database.transaction() as conn:
            conn.execute("UPDATE jobs SET slice_id = ? WHERE id = ?", (record["id"], job["id"]))
        jobs.log_event(job["id"], "sliced", f"{record['source_name']} with “{record['bundle_label']}”, "
                                            f"{BED_TYPES[record['bed_type']]}, {result['slicer_version']}")
        job_ids.append(job["id"])
    return job_ids


async def process_next() -> bool:
    """Slice the oldest queued model. Returns False when nothing was waiting."""
    with database.transaction() as conn:
        row = conn.execute("SELECT id FROM slices WHERE state = ? ORDER BY created_at, id LIMIT 1", (QUEUED,)).fetchone()
        if row is None:
            return False
        conn.execute("UPDATE slices SET state = ?, started_at = ?, error = NULL, exit_code = NULL WHERE id = ?",
                     (SLICING, time.time(), row["id"]))
    record = get_slice(row["id"])
    loop = asyncio.get_running_loop()
    try:
        result = await loop.run_in_executor(None, run_slice, record)
        job_ids = await loop.run_in_executor(None, _create_jobs, record, result)
    except Exception as e:
        _update(record["id"], state=FAILED, error=str(e) or type(e).__name__,
                exit_code=getattr(e, "exit_code", None), finished_at=time.time())
        print(f"[Slicer] {record['source_name']} failed: {e}")
    else:
        _update(record["id"], state=DONE, exit_code=result["exit_code"], slicer_version=result["slicer_version"],
                plates=len(result["plates"]), job_ids=json.dumps(job_ids), estimate_s=result["estimate_s"],
                estimate_g=result["estimate_g"], duration_ms=result["duration_ms"], finished_at=time.time())
        print(f"[Slicer] {record['source_name']} sliced in {result['duration_ms']} ms → job(s) {job_ids}")
        await jobs.broadcast()
    return True


async def worker_loop() -> None:
    """Background worker: slice queued models one at a time."""
    global _wakeup
    _wakeup = asyncio.Event()
    while True:
        _wakeup.clear()
        try:
            if await process_next():
                continue
        except Exception as e:  # the worker must survive anything a single slice throws
            print(f"[Slicer] Worker error: {e}")
        try:
            await asyncio.wait_for(_wakeup.wait(), timeout=30)
        except asyncio.TimeoutError:
            pass


def notify_worker() -> None:
    loop = state.loop
    if _wakeup is not None and loop is not None and loop.is_running():
        loop.call_soon_threadsafe(_wakeup.set)


