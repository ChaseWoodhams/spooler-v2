def orca_executable() -> Path | None:
    """ORCA_SLICER_PATH, else the newest tools/OrcaSlicer-*/orca-slicer.exe next to Spooler."""
    candidates = []
    if _orca_override is not None:
        candidates.append(_orca_override)
    if os.getenv("ORCA_SLICER_PATH", "").strip():
        candidates.append(Path(os.getenv("ORCA_SLICER_PATH").strip()))
    candidates += sorted((APP_DIR.parent / "tools").glob("OrcaSlicer-*/orca-slicer.exe"), reverse=True)
    return next((c for c in candidates if c.is_file()), None)


def require_orca() -> Path:
    orca = orca_executable()
    if orca is None:
        raise jobs.JobError("OrcaSlicer isn't installed — set ORCA_SLICER_PATH in Spooler's .env", 503)
    return orca


def init() -> None:
    """Migrate, requeue slices interrupted by a restart, and lock the default profile on first start."""
    database.migrate()
    with database.transaction() as conn:
        conn.execute("UPDATE slices SET state = ?, started_at = NULL WHERE state = ?", (QUEUED, SLICING))
    orca = orca_executable()
    if orca is None:
        print("[Slicer] OrcaSlicer not found — set ORCA_SLICER_PATH to enable slicing")
        return
    created = ensure_default_bundle()
    print(f"[Slicer] OrcaSlicer at {orca}" + (f"; locked profile “{created['label']}”" if created else ""))


