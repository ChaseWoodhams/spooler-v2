def safe_model_name(name: str) -> str:
    name = _UNSAFE_CHARS.sub("_", (name or "").replace("\\", "/").rsplit("/", 1)[-1].strip())
    stem, dot, suffix = name.rpartition(".")
    if not dot or f".{suffix.lower()}" not in MODEL_SUFFIXES:
        raise jobs.JobError("Upload an STL, 3MF, OBJ or STEP model")
    if not stem.strip("."):
        raise jobs.JobError("The model file needs a name")
    return f"{stem[:100]}.{suffix}"


