"""
G-code analysis for the job preview and preflight checks.

One pass over a G-code file produces:
  * the toolpath preview — extrusion paths per layer, compacted into a binary blob
  * bounds of what is actually printed (the slicer's start/end G-code is excluded,
    so the purge line and parking moves don't count) and a coarse occupancy grid
  * temperatures, embedded slicer settings and estimates
  * commands that don't belong in a normal print file

Toolpath format (little-endian): per path a header `<BH` (feature index, point
count) followed by that many `<HH` points. Coordinates are stored as
(mm + POINT_OFFSET) * POINT_SCALE. Each layer's paths sit at the byte range
given by its `offset` and `length`.
"""

import array
import base64
import hashlib
import math
import re
import struct
from pathlib import Path

from gcode_meta import read_estimates

ANALYSIS_VERSION = 3
POINT_SCALE      = 100    # 0.01 mm resolution
POINT_OFFSET     = 50.0   # mm; keeps slightly negative coordinates (purge lines) in unsigned range
MERGE_CHORD_MM   = 0.5    # consecutive tiny moves are merged into chords no longer than this
ARC_SEGMENT_MM   = 0.5
SAMPLE_STEP_MM   = 2.0    # long moves are sampled at this spacing for the occupancy grid
GRID_ORIGIN_MM   = -20    # occupancy grid covers GRID_ORIGIN_MM .. GRID_ORIGIN_MM + GRID_SIZE in X and Y
GRID_SIZE        = 320    # cells of 1 mm

CONFIG_KEYS = (
    "printer_model", "printer_settings_id", "print_settings_id", "filament_settings_id", "nozzle_diameter",
    "filament_type", "filament_colour", "curr_bed_type", "printable_area", "printable_height", "bed_exclude_area",
    "nozzle_temperature_range_low", "nozzle_temperature_range_high", "layer_height", "initial_layer_print_height",
    "gcode_flavor", "filament_diameter", "enable_prime_tower", "nozzle_type",
)

# Commands the stock OrcaSlicer/Elegoo Centauri Carbon start, end and print G-code uses, plus common harmless ones.
KNOWN_COMMANDS = frozenset({
    "G0", "G1", "G2", "G3", "G4", "G10", "G11", "G17", "G21", "G28", "G29", "G90", "G91", "G92",
    "M73", "M82", "M83", "M84", "M104", "M105", "M106", "M107", "M109", "M117", "M118", "M140", "M141",
    "M190", "M191", "M204", "M205", "M220", "M221", "M400", "M600", "M601", "M729", "M749", "M6211",
    "SET_VELOCITY_LIMIT", "SET_PRINT_STATS_INFO", "SET_PRESSURE_ADVANCE", "SET_HEATER_TEMPERATURE",
    "SET_FAN_SPEED", "EXCLUDE_OBJECT_DEFINE", "EXCLUDE_OBJECT_START", "EXCLUDE_OBJECT_END", "TIMELAPSE_TAKE_FRAME",
})

# Commands that change printer configuration, bypass safety limits or stop the machine.
DANGEROUS_COMMANDS = {
    "M500": "saves settings to the printer's memory",
    "M501": "reloads stored printer settings",
    "M502": "resets printer settings to factory defaults",
    "M92": "changes the motors' steps per millimetre",
    "M303": "runs heater PID tuning",
    "M112": "triggers an emergency stop",
    "M211": "changes the software endstops that keep the head inside the frame",
    "M302": "allows extruding with a cold nozzle",
    "M997": "starts a firmware update",
    "SAVE_CONFIG": "rewrites the printer configuration and restarts it",
    "FIRMWARE_RESTART": "restarts the printer firmware",
    "RESTART": "restarts the printer firmware",
    "SET_KINEMATIC_POSITION": "overrides the head position without homing",
    "RUN_SHELL_COMMAND": "runs a shell command on the printer",
}

_WORD = re.compile(r"([A-Za-z])\s*([-+]?(?:\d+\.?\d*|\.\d+))")
_GENERATED_BY = re.compile(r"^; generated by (.+?)(?: on \d{4}-\d{2}-\d{2}.*)?$")


def _words(code: str) -> dict:
    return {letter.upper(): float(value) for letter, value in _WORD.findall(code)}


def _klipper_params(code: str) -> dict:
    params = {}
    for token in code.split()[1:]:
        key, sep, value = token.partition("=")
        if sep:
            params[key.upper()] = value
    return params


class _Toolpath:
    """Accumulates extrusion paths per layer and packs them into the binary preview format."""

    def __init__(self):
        self.data = bytearray()
        self.features: list = []
        self._feature_index: dict = {}
        self.points: list = []
        self.feature = 0

    def feature_id(self, name: str) -> int:
        if name not in self._feature_index:
            if len(self.features) >= 255:
                return self._feature_index[self.features[-1]]
            self._feature_index[name] = len(self.features)
            self.features.append(name)
        return self._feature_index[name]

    def extend(self, start: tuple, end: tuple, feature: int) -> None:
        points = self.points
        if not points or points[-1] != start or feature != self.feature:
            self.flush()
            self.feature = feature
            points.append(start)
        if len(points) >= 2 and math.dist(points[-2], end) <= MERGE_CHORD_MM:
            points[-1] = end
        else:
            points.append(end)

    def flush(self) -> None:
        if len(self.points) >= 2:
            for chunk_start in range(0, len(self.points) - 1, 65534):
                chunk = self.points[chunk_start:chunk_start + 65535]
                encoded = array.array("H")
                for x, y in chunk:
                    encoded.append(min(65535, max(0, round((x + POINT_OFFSET) * POINT_SCALE))))
                    encoded.append(min(65535, max(0, round((y + POINT_OFFSET) * POINT_SCALE))))
                if encoded.itemsize != 2:
                    raise RuntimeError("unsigned short must be 2 bytes")
                self.data += struct.pack("<BH", self.feature, len(chunk))
                self.data += encoded.tobytes() if struct.pack("=H", 1) == struct.pack("<H", 1) else _swap(encoded)
        self.points.clear()  # in place: extend() holds a reference to this list


def _swap(values: array.array) -> bytes:
    swapped = array.array("H", values)
    swapped.byteswap()
    return swapped.tobytes()


def decode_toolpath(data: bytes, offset: int = 0, length: int | None = None) -> list:
    """[(feature index, [(x, y), …]), …] for a byte range of a toolpath blob (tests, debugging)."""
    end = len(data) if length is None else offset + length
    paths, pos = [], offset
    while pos < end:
        feature, count = struct.unpack_from("<BH", data, pos)
        pos += 3
        raw = struct.unpack_from(f"<{count * 2}H", data, pos)
        pos += count * 4
        paths.append((feature, [(raw[i] / POINT_SCALE - POINT_OFFSET, raw[i + 1] / POINT_SCALE - POINT_OFFSET)
                                for i in range(0, len(raw), 2)]))
    return paths


def grid_cells_in(analysis: dict, x0: float, y0: float, x1: float, y1: float) -> int:
    """Number of occupied 1 mm grid cells whose area overlaps the rectangle (mm)."""
    grid = base64.b64decode(analysis["occupancy"]["bits"])
    count = 0
    for gy in range(max(0, math.floor(y0 - GRID_ORIGIN_MM)), min(GRID_SIZE, math.ceil(y1 - GRID_ORIGIN_MM))):
        for gx in range(max(0, math.floor(x0 - GRID_ORIGIN_MM)), min(GRID_SIZE, math.ceil(x1 - GRID_ORIGIN_MM))):
            index = gy * GRID_SIZE + gx
            if grid[index >> 3] & (1 << (index & 7)):
                count += 1
    return count


def analyze(path: Path) -> tuple:
    """Analyse a G-code file. Returns (analysis dict, toolpath bytes)."""
    path = Path(path)
    digest = hashlib.sha256()
    toolpath = _Toolpath()
    grid = bytearray((GRID_SIZE * GRID_SIZE + 7) // 8)
    outside_grid = 0

    x = y = z = e = 0.0
    absolute_xyz, relative_e = True, False
    feature_name = "Unknown"
    feature = toolpath.feature_id(feature_name)
    in_custom = False

    layers: list = []
    layer = None
    layer_markers = False

    model_min = [math.inf, math.inf, math.inf]
    model_max = [-math.inf, -math.inf, -math.inf]
    travel_min = [math.inf, math.inf]
    travel_max = [-math.inf, -math.inf]

    config: dict = {}
    in_config = False
    header: dict = {"slicer": None, "thumbnail": False}
    temps = {"nozzle": [], "bed": [], "chamber": []}
    nozzle_events: list = []  # (line number, target) — to find the temperature printing starts at
    commands: dict = {}
    unknown: dict = {}
    findings: list = []       # (line number, command, reason, level)
    motors_off_lines: list = []
    homing_lines: list = []
    stats = {"lines": 0, "moves": 0, "extrusion_moves": 0, "retractions": 0, "extruded_mm": 0.0,
             "max_extrusion_speed_mm_s": 0.0, "arcs": 0, "unsupported_arcs": 0}
    feedrate = 0.0
    first_extrusion_line = last_extrusion_line = None
    feature_stats: dict = {}  # feature name → [extruded filament mm, extrusion time s]

    def mark(px: float, py: float) -> None:
        nonlocal outside_grid
        gx, gy = math.floor(px - GRID_ORIGIN_MM), math.floor(py - GRID_ORIGIN_MM)
        if 0 <= gx < GRID_SIZE and 0 <= gy < GRID_SIZE:
            index = gy * GRID_SIZE + gx
            grid[index >> 3] |= 1 << (index & 7)
        else:
            outside_grid += 1

    def start_layer(at_z: float) -> dict:
        previous = layers[-1]["z"] if layers else 0.0
        new_layer = {"z": round(at_z, 3), "height": round(at_z - previous, 3), "extruded_mm": 0.0,
                     "offset": len(toolpath.data), "length": 0, "moves": 0}
        layers.append(new_layer)
        return new_layer

    def close_layer() -> None:
        if layer is not None:
            toolpath.flush()
            layer["length"] = len(toolpath.data) - layer["offset"]
            layer["extruded_mm"] = round(layer["extruded_mm"], 2)

    def temperature(kind: str, value: float, line_no: int) -> None:
        temps[kind].append(value)
        if kind == "nozzle":
            nozzle_events.append((line_no, value))

    def extrude_segment(x0, y0, x1, y1, z1, amount, line_no) -> None:
        nonlocal layer, first_extrusion_line, last_extrusion_line
        stats["extruded_mm"] += amount
        if in_custom:
            return
        totals = feature_stats.setdefault(feature_name, [0.0, 0.0])
        totals[0] += amount
        if feedrate > 0:
            totals[1] += math.hypot(x1 - x0, y1 - y0) * 60 / feedrate
        if layer is None or (not layer_markers and z1 > layer["z"] + 0.005):
            close_layer()
            layer = start_layer(z1)
        layer["extruded_mm"] += amount
        layer["moves"] += 1
        first_extrusion_line = first_extrusion_line or line_no
        last_extrusion_line = line_no
        for px, py in ((x0, y0), (x1, y1)):
            model_min[0], model_max[0] = min(model_min[0], px), max(model_max[0], px)
            model_min[1], model_max[1] = min(model_min[1], py), max(model_max[1], py)
        model_min[2], model_max[2] = min(model_min[2], z1), max(model_max[2], z1)
        length = math.hypot(x1 - x0, y1 - y0)
        steps = max(1, math.ceil(length / SAMPLE_STEP_MM))
        for i in range(steps + 1):
            mark(x0 + (x1 - x0) * i / steps, y0 + (y1 - y0) * i / steps)
        toolpath.extend((x0, y0), (x1, y1), feature)

    with path.open("rb") as fh:
        for line_no, raw in enumerate(fh, start=1):
            digest.update(raw)
            line = raw.decode("utf-8", errors="replace").strip()
            stats["lines"] += 1
            if not line:
                continue
            code, _, comment = line.partition(";")
            code = code.strip()

            if not code:
                text = comment.strip()
                if in_config:
                    key, sep, value = text.partition(" = ")
                    if sep and key in CONFIG_KEYS:
                        config[key] = value.strip().strip('"')
                    elif text.startswith("CONFIG_BLOCK_END"):
                        in_config = False
                elif text.startswith("TYPE:"):
                    feature_name = text[5:].strip() or "Unknown"
                    in_custom = feature_name == "Custom"
                    feature = toolpath.feature_id(feature_name)
                elif text == "LAYER_CHANGE":
                    layer_markers = True
                elif text.startswith("Z:") and layer_markers:
                    try:
                        marker_z = float(text[2:])
                    except ValueError:
                        marker_z = None
                    if marker_z is not None:
                        close_layer()
                        layer = start_layer(marker_z)
                elif text.startswith("CONFIG_BLOCK_START"):
                    in_config = True
                elif text.startswith(("THUMBNAIL_BLOCK_START", "thumbnail begin", "thumbnail_JPG begin",
                                      "thumbnail_QOI begin")):
                    header["thumbnail"] = True
                elif header["slicer"] is None and text.startswith("generated by"):
                    match = _GENERATED_BY.match("; " + text)
                    header["slicer"] = match.group(1) if match else text[13:]
                continue

            name = code.split(None, 1)[0].upper()
            if name[0] == "T" and name[1:].isdigit():
                commands[name] = commands.get(name, 0) + 1
                continue
            commands[name] = commands.get(name, 0) + 1
            if name not in KNOWN_COMMANDS:
                if name in DANGEROUS_COMMANDS:
                    findings.append((line_no, name, DANGEROUS_COMMANDS[name], "fail"))
                else:
                    unknown[name] = unknown.get(name, 0) + 1
                continue

            if name in ("G0", "G1", "G2", "G3"):
                words = _words(code)
                stats["moves"] += 1
                if "F" in words:
                    feedrate = words["F"]
                if absolute_xyz:
                    nx, ny, nz = words.get("X", x), words.get("Y", y), words.get("Z", z)
                else:
                    nx, ny, nz = x + words.get("X", 0.0), y + words.get("Y", 0.0), z + words.get("Z", 0.0)
                de = 0.0
                if "E" in words:
                    de = words["E"] if relative_e else words["E"] - e
                    e = e + words["E"] if relative_e else words["E"]
                moved_xy = nx != x or ny != y
                travel_min[0], travel_max[0] = min(travel_min[0], nx), max(travel_max[0], nx)
                travel_min[1], travel_max[1] = min(travel_min[1], ny), max(travel_max[1], ny)

                if name in ("G2", "G3") and ("I" in words or "J" in words):
                    stats["arcs"] += 1
                    cx, cy = x + words.get("I", 0.0), y + words.get("J", 0.0)
                    radius = math.hypot(x - cx, y - cy)
                    start_angle = math.atan2(y - cy, x - cx)
                    end_angle = math.atan2(ny - cy, nx - cx)
                    sweep = end_angle - start_angle
                    if name == "G2":  # clockwise
                        sweep = sweep - 2 * math.pi if sweep >= 0 else sweep
                    else:
                        sweep = sweep + 2 * math.pi if sweep <= 0 else sweep
                    steps = max(1, min(720, math.ceil(abs(sweep) * radius / ARC_SEGMENT_MM)))
                    px, py = x, y
                    for i in range(1, steps + 1):
                        angle = start_angle + sweep * i / steps
                        qx = cx + radius * math.cos(angle) if i < steps else nx
                        qy = cy + radius * math.sin(angle) if i < steps else ny
                        qz = z + (nz - z) * i / steps
                        travel_min[0], travel_max[0] = min(travel_min[0], qx), max(travel_max[0], qx)
                        travel_min[1], travel_max[1] = min(travel_min[1], qy), max(travel_max[1], qy)
                        if de > 0:
                            extrude_segment(px, py, qx, qy, qz, de / steps, line_no)
                        px, py = qx, qy
                elif name in ("G2", "G3"):
                    stats["unsupported_arcs"] += 1
                    if de > 0 and moved_xy:
                        extrude_segment(x, y, nx, ny, nz, de, line_no)
                elif de > 0 and moved_xy:
                    extrude_segment(x, y, nx, ny, nz, de, line_no)

                if de > 0 and moved_xy:
                    stats["extrusion_moves"] += 1
                    if feedrate:
                        stats["max_extrusion_speed_mm_s"] = max(stats["max_extrusion_speed_mm_s"], feedrate / 60)
                elif de < 0 and not moved_xy:
                    stats["retractions"] += 1
                x, y, z = nx, ny, nz
            elif name == "G92":
                words = _words(code)
                x, y, z, e = words.get("X", x), words.get("Y", y), words.get("Z", z), words.get("E", e)
            elif name == "G90":
                absolute_xyz = True
            elif name == "G91":
                absolute_xyz = False
            elif name == "M82":
                relative_e = False
            elif name == "M83":
                relative_e = True
            elif name == "G28":
                homing_lines.append(line_no)
            elif name == "M84":
                motors_off_lines.append(line_no)
            elif name in ("M104", "M109", "M140", "M190", "M141", "M191"):
                words = _words(code)
                if "S" in words:
                    kind = "nozzle" if name in ("M104", "M109") else "bed" if name in ("M140", "M190") else "chamber"
                    temperature(kind, words["S"], line_no)
            elif name == "SET_HEATER_TEMPERATURE":
                params = _klipper_params(code)
                heater = params.get("HEATER", "").lower()
                try:
                    target = float(params.get("TARGET", ""))
                except ValueError:
                    target = None
                if target is not None:
                    kind = "nozzle" if heater.startswith("extruder") else "bed" if "bed" in heater else "chamber"
                    temperature(kind, target, line_no)
            elif name in ("M220", "M221"):
                words = _words(code)
                value = words.get("S")
                limits = (10, 300) if name == "M220" else (50, 150)
                if value is not None and not limits[0] <= value <= limits[1]:
                    what = "speed" if name == "M220" else "flow"
                    findings.append((line_no, name, f"sets {what} to {value:g}%", "warn"))
    close_layer()
    toolpath.flush()

    at_print_start = None
    if first_extrusion_line is not None:
        for line_no in motors_off_lines:
            if line_no < last_extrusion_line:
                findings.append((line_no, "M84", "turns the motors off in the middle of the print", "fail"))
        for line_no in homing_lines:
            if line_no > first_extrusion_line and len(layers) > 1:
                findings.append((line_no, "G28", "homes the axes after printing has started", "warn"))
        before = [value for line_no, value in nozzle_events if line_no < first_extrusion_line and value > 0]
        at_print_start = before[-1] if before else None

    def rounded(values):
        return [round(v, 2) for v in values]

    temperatures = {
        kind: {"max": max(values), "first": next((v for v in values if v > 0), None), "values": sorted(set(values))}
        if values else None
        for kind, values in temps.items()
    }
    if temperatures["nozzle"]:
        temperatures["nozzle"]["at_print_start"] = at_print_start

    analysis = {
        "version":   ANALYSIS_VERSION,
        "sha256":    digest.hexdigest(),
        "size":      path.stat().st_size,
        "slicer":    header["slicer"],
        "thumbnail": header["thumbnail"],
        "config":    config,
        "estimates": read_estimates(path),
        "layers":    [l for l in layers if l["moves"] or l["length"]],
        "features":  toolpath.features,
        "feature_stats": {name: {"extruded_mm": round(totals[0], 1), "time_s": round(totals[1])}
                          for name, totals in feature_stats.items()},
        "bounds": {
            "model":  {"min": rounded(model_min), "max": rounded(model_max)} if model_min[0] != math.inf else None,
            "travel": {"min": rounded(travel_min), "max": rounded(travel_max)} if travel_min[0] != math.inf else None,
        },
        "occupancy": {"origin_mm": GRID_ORIGIN_MM, "size": GRID_SIZE, "cell_mm": 1,
                      "bits": base64.b64encode(bytes(grid)).decode(), "outside": outside_grid},
        "temperatures":     temperatures,
        "commands":         commands,
        "unknown_commands": unknown,
        "findings": [{"line": n, "command": c, "reason": r, "level": lvl} for n, c, r, lvl in findings],
        "stats": {**stats, "extruded_mm": round(stats["extruded_mm"], 2),
                  "max_extrusion_speed_mm_s": round(stats["max_extrusion_speed_mm_s"], 1)},
    }
    return analysis, bytes(toolpath.data)
