#!/usr/bin/env node
// Builds the CSS variable blocks in public/style.css from tokens/spooler.tokens.json (DTCG).
//   node scripts/build-tokens.cjs          rewrite the generated regions
//   node scripts/build-tokens.cjs --check  exit 1 if the committed CSS is stale
const fs = require('fs');
const path = require('path');

const root = path.join(__dirname, '..');
const tokensPath = path.join(root, 'tokens', 'spooler.tokens.json');
const cssPath = path.join(root, 'public', 'style.css');
const check = process.argv.includes('--check');

const tokens = JSON.parse(fs.readFileSync(tokensPath, 'utf8'));

// Collect the leaf tokens of one region, keeping JSON order. Group-level $type is inherited.
function leaves(node, type, out = []) {
  for (const [key, val] of Object.entries(node)) {
    if (key.startsWith('$')) continue;
    if (val && typeof val === 'object' && '$value' in val) out.push({ name: key, type: val.$type || type, token: val });
    else if (val && typeof val === 'object') leaves(val, val.$type || type, out);
  }
  return out;
}

const zero = s => (/^0(px)?$/.test(s) ? '0' : s);
function format(value, type) {
  if (typeof value === 'string') {
    const alias = value.match(/^\{(.+)\}$/);
    if (alias) return `var(--${alias[1].split('.').pop()})`;
    return value;
  }
  if (type === 'shadow') {
    const parts = [zero(value.offsetX), zero(value.offsetY), zero(value.blur)];
    if (zero(value.spread || '0') !== '0') parts.push(value.spread);
    return `${parts.join(' ')} ${value.color}`;
  }
  throw new Error(`Unsupported ${type} value: ${JSON.stringify(value)}`);
}

function declaration(name, value, type, description) {
  const note = description ? ` /* ${description} */` : '';
  return `  --${name}: ${format(value, type)};${note}`;
}

function region(name) {
  const list = leaves(tokens[name], undefined);
  const dark = [];
  const light = [];
  for (const { name: n, type, token } of list) {
    const mode = (token.$extensions && token.$extensions.mode) || {};
    if (mode.dark !== null) dark.push(declaration(n, mode.dark !== undefined ? mode.dark : token.$value, type, token.$description));
    if (mode.light !== undefined) light.push(declaration(n, mode.light, type));
  }
  const lines = [
    `/* tokens:start ${name} - generated by scripts/build-tokens.cjs from tokens/spooler.tokens.json; edit the JSON, not this block */`,
    ':root {', ...dark, '}',
    'body.light-mode {', ...light, '}',
    `/* tokens:end ${name} */`,
  ];
  return lines.join('\n');
}

let css = fs.readFileSync(cssPath, 'utf8');
const eol = css.includes('\r\n') ? '\r\n' : '\n';
css = css.replace(/\r\n/g, '\n');
let changed = false;
for (const name of Object.keys(tokens).filter(k => !k.startsWith('$'))) {
  const re = new RegExp(`/\\* tokens:start ${name} [\\s\\S]*?/\\* tokens:end ${name} \\*/`);
  if (!re.test(css)) throw new Error(`style.css has no tokens:start/tokens:end markers for "${name}"`);
  const next = css.replace(re, () => region(name));
  if (next !== css) changed = true;
  css = next;
}

if (check) {
  if (changed) {
    console.error('tokens: public/style.css is stale. Run `npm run tokens:build` and commit the result.');
    process.exit(1);
  }
  console.log('tokens: style.css is up to date');
} else {
  fs.writeFileSync(cssPath, css.replace(/\n/g, eol));
  console.log(changed ? 'tokens: style.css updated' : 'tokens: style.css already up to date');
}
