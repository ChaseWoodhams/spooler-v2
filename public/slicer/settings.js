/* Spooler slicer – settings panel rendered from OrcaSlicer's own setting definitions and tab layout
   (public/orca/settings.json, generated by tools/orca_settings.py). */

import { evaluate } from "./rules.js";

const HIDDEN_PAGES = new Set(["Multimaterial", "Dependencies", "Notes"]);
const HIDDEN_KEYS = new Set(["post_process", "filename_format", "compatible_printers", "compatible_prints", "inherits"]);

const esc = s => String(s ?? "").replace(/[&<>"']/g, c => ({ "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;", "'": "&#39;" }[c]));
const first = value => (Array.isArray(value) ? value[0] : value);

export class SettingsPanel {
  constructor({ tabs, pages, body, search, mode, onChange, onReset, onTab }) {
    Object.assign(this, { tabsEl: tabs, pagesEl: pages, bodyEl: body, searchEl: search, modeEl: mode, onChange, onReset, onTab });
    this.schema = null;
    this.context = null;
    this.page = {};
    this.searchEl.addEventListener("input", () => this.render());
    this.modeEl.addEventListener("change", () => this.render());
    this.pagesEl.addEventListener("click", e => {
      const btn = e.target.closest("[data-page]");
      if (!btn || !this.context) return;
      this.page[this.context.tab] = btn.dataset.page;
      this.render();
    });
    this.tabsEl.addEventListener("click", e => {
      const btn = e.target.closest("[data-tab]");
      if (btn) this.onTab?.(btn.dataset.tab);
    });
    this.tabsEl.addEventListener('keydown', e => {
      if (!['ArrowLeft','ArrowRight','Home','End'].includes(e.key)) return;
      const tabs=[...this.tabsEl.querySelectorAll('[role="tab"]')];
      const at=tabs.indexOf(e.target); if(at<0)return;
      e.preventDefault();
      const index=e.key==='Home'?0:e.key==='End'?tabs.length-1:(at+(e.key==='ArrowRight'?1:-1)+tabs.length)%tabs.length;
      const id=tabs[index].dataset.tab;
      this.onTab?.(id);
      this.tabsEl.querySelector(`[data-tab="${id}"]`)?.focus();
    });
    this.bodyEl.addEventListener("change", e => this._changed(e.target));
    this.bodyEl.addEventListener("click", e => {
      const btn = e.target.closest("[data-reset]");
      if (btn && this.context) this.onReset?.(this.context.target, btn.dataset.reset.split(","));
    });
  }

  setSchema(schema) {
    this.schema = schema;
  }

  /* context: { tab: "process" | "filament" | "object", tabs: [{id, label}], layout: "process" | "filament",
                base: {key: value}, changes: {key: value}, target: an opaque value passed back to onChange/onReset,
                note: optional text shown above the settings } */
  show(context) {
    this.context = context;
    this.render();
  }

  _visible(key, meta) {
    if (!meta || HIDDEN_KEYS.has(key) || key.endsWith("_gcode") || meta.readonly || meta.type === "point" || meta.type === "none") return false;
    const rank = { simple: 0, advanced: 1, expert: 2 };  // "develop" settings are never shown
    const shown = rank[this.modeEl.value] ?? 0;
    return (rank[meta.mode || "simple"] ?? 0) <= shown;
  }

  _value(key) {
    const { changes, base } = this.context;
    return key in changes ? changes[key] : base[key];
  }

  render() {
    const ctx = this.context;
    if (!this.schema || !ctx) return;
    this.tabsEl.innerHTML = ctx.tabs.map(t =>
      `<button class="btn btn-secondary btn-sm${t.id === ctx.tab ? " active" : ""}" type="button" role="tab" aria-selected="${t.id === ctx.tab}" tabindex="${t.id === ctx.tab ? 0 : -1}" aria-controls="settings-body" data-tab="${t.id}">${esc(t.label)}</button>`).join("");
    this.bodyEl.setAttribute('role','tabpanel');
    this.bodyEl.setAttribute('aria-label',ctx.tabs.find(t=>t.id===ctx.tab)?.label || 'Settings');
    const options = this.schema.options;
    const query = this.searchEl.value.trim().toLowerCase();
    // OrcaSlicer greys out or hides settings that depend on others (rules.js); only process settings have such rules
    this.toggles = ctx.layout === "process" ? evaluate(key => first(this._value(key))) : { hidden: new Set(), disabled: new Set() };
    const pages = (this.schema.tabs[ctx.layout] || []).filter(p => !HIDDEN_PAGES.has(p.page));
    const rowsOf = page => page.groups.map(group => ({
      group: group.group,
      rows: group.rows.map(row => ({ ...row, options: row.options.filter(key => this._visible(key, options[key]) && !this.toggles.hidden.has(key)) }))
        .filter(row => row.options.length && (!query || row.options.some(key => {
          const meta = options[key];
          return [key, meta.label, meta.full_label, meta.tooltip, row.label].some(t => t && t.toLowerCase().includes(query));
        }))),
    })).filter(g => g.rows.length);

    const changedCount = page => page.groups.reduce((n, g) => n + g.rows.reduce((m, r) => m + r.options.filter(k => k in ctx.changes).length, 0), 0);
    const visiblePages = pages.filter(p => rowsOf(p).length);
    let current = this.page[ctx.tab];
    if (!visiblePages.some(p => p.page === current)) current = visiblePages[0]?.page;
    this.pagesEl.hidden = !!query;
    this.pagesEl.innerHTML = visiblePages.map(p => {
      const count = changedCount(p);
      return `<button type="button" data-page="${esc(p.page)}" class="${p.page === current ? "active" : ""}">${esc(p.page)}${count ? `<span class="count">${count}</span>` : ""}</button>`;
    }).join("");

    const shown = query ? visiblePages : visiblePages.filter(p => p.page === current);
    const html = [];
    if (ctx.note) html.push(`<p class="set-note">${esc(ctx.note)}</p>`);
    for (const page of shown) {
      for (const group of rowsOf(page)) {
        html.push(`<div class="set-group"><h5>${query ? `${esc(page.page)} › ` : ""}${esc(group.group)}</h5>`);
        for (const row of group.rows) html.push(this._row(row, options));
        html.push("</div>");
      }
    }
    if (!html.length || (html.length === 1 && ctx.note)) html.push(`<p class="set-note">${query ? "No settings match." : "No settings on this page."}</p>`);
    this.bodyEl.innerHTML = html.join("");
  }

  _row(row, options) {
    const ctx = this.context;
    const keys = row.options;
    const single = keys.length === 1;
    const meta0 = options[keys[0]];
    const label = row.label || meta0.full_label || meta0.label || keys[0];
    const modified = keys.some(key => key in ctx.changes);
    const disabled = keys.every(key => this.toggles.disabled.has(key));
    const tooltip = keys.map(key => `${options[key].label || key}${options[key].tooltip ? `: ${options[key].tooltip}` : ""} [${key}]`).join("\n\n");
    const fields = keys.map(key => this._field(key, options[key], single, this.toggles.disabled.has(key), label)).join("");
    return `<div class="set-row${modified ? " modified" : ""}${disabled ? " disabled" : ""}">
      <div class="set-label" title="${esc(tooltip)}">${esc(label)}${modified ? '<small> · modified</small>' : ''}</div>
      <div class="set-fields">${fields}</div>
      <button type="button" class="set-reset" aria-label="Reset ${esc(label)} to inherited value" data-reset="${esc(keys.join(","))}" title="Back to the profile's value">↺</button>
    </div>`;
  }

  _field(key, meta, single, disabled, rowLabel = "") {
    const raw = first(this._value(key));
    const value = raw === undefined || raw === null ? "" : String(raw);
    const dis = disabled ? " disabled" : "";
    const name = single || !rowLabel ? (rowLabel || meta.label || key) : `${rowLabel} – ${meta.label || key}`;
    const aria = ` aria-label="${esc(name)}"`;
    let control;
    if (meta.type === "bool") {
      control = `<input type="checkbox" data-key="${key}"${aria}${value === "1" || value === "true" ? " checked" : ""}${dis}>`;
    } else if (meta.type === "enum") {
      const choices = meta.enum || [];
      const extra = value && !choices.some(([v]) => v === value) ? `<option value="${esc(value)}" selected>${esc(value)}</option>` : "";
      control = `<select data-key="${key}"${aria}${dis}>${choices.map(([v, l]) =>
        `<option value="${esc(v)}"${v === value ? " selected" : ""}>${esc(l)}</option>`).join("")}${extra}</select>`;
    } else {
      control = `<input type="text" data-key="${key}"${aria} value="${esc(value)}" placeholder="default"${meta.type !== "string" ? ' inputmode="decimal"' : ""}${dis}>`;
    }
    const unit = meta.sidetext ? `<span class="set-unit">${esc(meta.sidetext)}</span>` : "";
    if (single) return `${control}${unit}`;
    return `<span class="set-field" title="${esc(meta.label || key)}"><small>${esc(meta.label || key)}</small>${control}${unit}</span>`;
  }

  _changed(input) {
    const key = input.dataset?.key;
    if (!key || !this.context) return;
    const meta = this.schema.options[key] || {};
    let value = input.type === "checkbox" ? (input.checked ? "1" : "0") : input.value.trim();
    if (["int", "float", "percent", "float_or_percent"].includes(meta.type)) {
      const number = Number(value.replace("%", ""));
      const ok = value !== "" && Number.isFinite(number) && (meta.type !== "int" || Number.isInteger(number))
        && (!value.endsWith("%") || ["percent", "float_or_percent"].includes(meta.type))
        && (meta.min === undefined || value.endsWith("%") && meta.type !== "percent" || number >= meta.min)
        && (meta.max === undefined || value.endsWith("%") && meta.type !== "percent" || number <= meta.max);
      input.classList.toggle("invalid", !ok);
      input.setAttribute('aria-invalid',String(!ok));
      if (!ok) {
        input.title = meta.min !== undefined || meta.max !== undefined
          ? `Enter a number${meta.min !== undefined ? ` from ${meta.min}` : ""}${meta.max !== undefined ? ` up to ${meta.max}` : ""}` : "Enter a number";
        return;
      }
      if (meta.type === "percent" && !value.endsWith("%")) value = `${value}%`;
    }
    const base = this.context.base[key];
    this.onChange?.(this.context.target, key, Array.isArray(base) || meta.vector ? [value] : value);
  }
}
